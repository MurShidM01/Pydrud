"""Ownership-aware writing for generated Android files.

A generated file is a starting point, not a contract: developers add Gradle
dependencies, permissions and ProGuard rules. `pydrud sync` must therefore
never silently destroy an edit, while still applying everything that
`pydrud.yaml` implies.

Three strategies, chosen per file by how much of it Pydrud really owns:

* **Managed regions** - the manifest (permissions, features, services),
  ProGuard rules and the Gradle dependency block are flat lists. Pydrud owns
  the text between `pydrud:<name>:begin` and `pydrud:<name>:end` and
  replaces only that; every other line is the developer's.
* **Hash stamps** - files Pydrud owns end to end (Java classes, resources,
  Gradle scripts, wrapper). The first line records a hash of the body:

      // GENERATED by pydrud sync - do not edit. pydrud-hash: 3f2a...

  Hash matches -> nobody edited it -> rewrite with the new version.
  Hash differs -> local edits -> keep the file, write the new version next
  to it as `<name>.pydrud-new` and report a conflict.
  No stamp at all -> a file from an older Pydrud. Adopt it only when it
  still matches what we would generate; otherwise treat it as edited.
* **Ensure-only** - `gradle.properties`. Pydrud adds the keys it needs and
  never touches a key the developer already set.

The manifest is written without a stamp: it is meant to be edited by hand,
so claiming ownership of the whole file would be a lie.
"""

from __future__ import annotations

import hashlib
import os
import re
from collections import Counter
from dataclasses import dataclass, field
from typing import Callable, Optional

MARKER = "GENERATED by pydrud sync"
CONFLICT_SUFFIX = ".pydrud-new"

#: Marker a patch returns when it could not apply everything.
NEEDS_REVIEW = "needs review"

_HASH = re.compile(r"pydrud-hash:\s*([0-9a-f]{16,64})")
_XML_DECL = re.compile(r"^\s*<\?xml[^>]*\?>")

#: comment wrapper per file family: (prefix, suffix)
_COMMENTS = {
    "java": ("// ", ""),
    "kotlin": ("// ", ""),
    "xml": ("<!-- ", " -->"),
    "hash": ("# ", ""),
    "bat": ("@rem ", ""),
}

#: A patch turns (current body, freshly rendered body) into (merged, notes).
Patch = Callable[[str, str], "tuple[str, list[str]]"]


def body_hash(text: str) -> str:
    """Stable short hash of a file body (header excluded)."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:32]


def _comment(style: str, text: str) -> str:
    prefix, suffix = _COMMENTS.get(style, _COMMENTS["hash"])
    return f"{prefix}{text}{suffix}"


def stamp(content: str, style: str) -> str:
    """Prepend the generated header, hashing the body as written."""
    digest = body_hash(content)
    header = _comment(style, f"{MARKER} - do not edit. pydrud-hash: {digest}") + "\n"
    if content.startswith("#!"):
        # gradlew: the shebang has to stay on line one or the script will not
        # run, so the header goes directly below it.
        first, _, rest = content.partition("\n")
        return first + "\n" + header + rest
    if style == "xml":
        match = _XML_DECL.match(content)
        if match:
            end = match.end()
            return content[:end] + "\n" + header + content[end:].lstrip("\n")
    return header + content


def split_stamp(text: str) -> tuple[str, Optional[str]]:
    """Return the body and its recorded hash, with the header removed."""
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        match = _HASH.search(line)
        if match:
            return "".join(lines[:index] + lines[index + 1:]), match.group(1)
    return text, None


def is_user_modified(path: str) -> bool:
    """True when the file on disk no longer matches its recorded hash."""
    try:
        with open(path, encoding="utf-8") as handle:
            body, stored = split_stamp(handle.read())
    except OSError:
        return False
    return stored is not None and body_hash(body) != stored


def _write(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)


def _read(path: str) -> Optional[str]:
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except OSError:
        return None


@dataclass(frozen=True)
class Outcome:
    """What happened to one file, plus anything worth reporting."""

    status: str          # created | unchanged | updated | merged | conflict
    notes: tuple[str, ...] = ()


@dataclass
class ChangeLog:
    """Aggregated result of one sync, for the closing summary."""

    counts: Counter = field(default_factory=Counter)
    notes: list[str] = field(default_factory=list)

    def add(self, outcome: Outcome) -> None:
        self.counts[outcome.status] += 1
        self.notes.extend(outcome.notes)

    @property
    def written(self) -> int:
        return self.counts["created"] + self.counts["updated"] + self.counts["merged"]

    @property
    def conflicts(self) -> int:
        return self.counts["conflict"]

    def summary(self) -> str:
        parts = []
        for status, label in (("created", "created"), ("updated", "updated"),
                              ("merged", "merged"), ("unchanged", "unchanged")):
            if self.counts[status]:
                parts.append(f"{self.counts[status]} {label}")
        return ", ".join(parts) or "nothing to do"


def write_generated(
    path: str,
    content: str,
    style: str,
    *,
    force: bool = False,
    patch: Optional[Patch] = None,
) -> Outcome:
    """Write *content* under the ownership rules described in the module doc."""
    stamped = stamp(content, style)
    current = _read(path)
    if current is None:
        _write(path, stamped)
        return Outcome("created")
    if current == stamped:
        return Outcome("unchanged")

    body, stored = split_stamp(current)
    legacy = stored is None
    if legacy:
        # No provenance: the file predates ownership tracking, so it was
        # written by an older Pydrud and is ours to upgrade. Every project
        # gets stamped on its first sync, so this is a one-time migration.
        untouched = body == content
    else:
        untouched = body_hash(body) == stored

    if force or untouched:
        # Nobody edited it, so the freshly rendered version is authoritative.
        _write(path, stamped)
        return Outcome("updated")

    if patch is not None:
        merged, notes = patch(body, content)
        if NEEDS_REVIEW in notes:
            # A structural change the line patcher cannot make (a new plugin,
            # a flavor dimension). A file with no provenance is ours to
            # upgrade; a stamped one was edited, so keep it and leave the
            # rendered version beside it.
            notes = [note for note in notes if note != NEEDS_REVIEW]
            if legacy:
                _write(path, stamped)
                return Outcome("updated", tuple(notes))
            _write(path + CONFLICT_SUFFIX, stamped)
            return Outcome("conflict", tuple(notes))
        if merged != body:
            _write(path, stamp(merged, style))
            return Outcome("merged", tuple(notes))
        if legacy:
            _write(path, stamped)
            return Outcome("updated", tuple(notes))
        # Everything the patch can apply is already applied; whatever is left
        # is the developer's own content, not a conflict.
        return Outcome("unchanged", tuple(notes))

    if legacy:
        _write(path, stamped)
        return Outcome("updated")
    _write(path + CONFLICT_SUFFIX, stamped)
    return Outcome("conflict")


def write_patched(path: str, content: str, patch: Patch) -> Outcome:
    """Merge *content* into the file at *path* and write only on change.

    Used for files Pydrud shares with the developer (manifest, gradle
    properties): they carry no provenance header, so the merge itself is the
    contract.
    """
    current = _read(path)
    if current is None:
        _write(path, content)
        return Outcome("created")
    merged, notes = patch(current, content)
    if merged == current:
        return Outcome("unchanged", tuple(notes))
    _write(path, merged)
    return Outcome("merged", tuple(notes))




# ── Managed regions ──────────────────────────────────────────────────────
#
# A region is a flat list Pydrud owns completely:
#
#     <!-- pydrud:permissions:begin -->
#     <uses-permission android:name="android.permission.CAMERA" />
#     <!-- pydrud:permissions:end -->
#
# Replacing the region keeps every surrounding line, so a developer can add
# their own entries above or below it and sync will not touch them.

def region_markers(kind: str, style: str = "xml") -> tuple[str, str]:
    prefix, suffix = _COMMENTS.get(style, _COMMENTS["hash"])
    return (f"{prefix}pydrud:{kind}:begin{suffix}",
            f"{prefix}pydrud:{kind}:end{suffix}")


def _region_pattern(kind: str, style: str = "xml") -> re.Pattern:
    begin, end = region_markers(kind, style)
    return re.compile(
        r"([ \t]*)" + re.escape(begin) + r"(.*?)" + re.escape(end)
        + r"[ \t]*\n?",
        re.DOTALL)


def extract_region(text: str, kind: str, style: str = "xml") -> Optional[str]:
    """Return the text between a region's markers, or None when absent."""
    begin, end = region_markers(kind, style)
    match = re.search(
        re.escape(begin) + r"(.*?)" + re.escape(end), text, re.DOTALL)
    return match.group(1) if match else None


def replace_region(text: str, kind: str, block: str, style: str = "xml") -> str:
    """Swap a region's body for *block*; remove it when *block* is empty."""
    match = _region_pattern(kind, style).search(text)
    if match is None:
        return text
    if not block:
        return text[:match.start()] + text[match.end():]
    begin, end = region_markers(kind, style)
    indent = match.group(1)
    replacement = indent + begin + "\n" + block + indent + end + "\n"
    return text[:match.start()] + replacement + text[match.end():]


def _block(body: str) -> str:
    """Normalise a region body: no blank first line, one trailing newline."""
    body = body.strip("\n")
    if not body.strip():
        return ""
    return body.rstrip() + "\n"


def _wrapped(kind: str, body: str, style: str = "xml") -> str:
    """A region as it appears in a file: markers plus body."""
    begin, end = region_markers(kind, style)
    return begin + "\n" + body + end + "\n"


# ── Manifest ─────────────────────────────────────────────────────────────

_OPEN_MANIFEST = re.compile(r"<manifest\b[^>]*>")
_APPLICATION = re.compile(r"<application\b[^>]*>")
_ACTIVITY_BLOCK = re.compile(
    r"<activity\b[^>]*>(?:(?!</activity>).)*</activity>", re.DOTALL)

#: Regions the manifest owns, in insertion order.
_MANIFEST_REGIONS = ("permissions", "activity", "services")


def _launcher_activity(text: str):
    """The activity element that carries the MAIN/LAUNCHER filter."""
    for match in _ACTIVITY_BLOCK.finditer(text):
        if "android.intent.action.MAIN" in match.group(0):
            return match
    return None

def _attr(element: str, name: str) -> Optional[str]:
    match = re.search(rf'{re.escape(name)}\s*=\s*"([^"]*)"', element)
    return match.group(1) if match else None


def _set_attr(element: str, name: str, value: str) -> str:
    pattern = re.compile(rf'({re.escape(name)}\s*=\s*")([^"]*)(")')
    if not pattern.search(element):
        return element
    return pattern.sub(lambda m: m.group(1) + value + m.group(3), element, count=1)


def merge_manifest(existing: str, rendered: str) -> tuple[str, list[str]]:
    """Apply the rendered manifest to *existing* without losing local edits.

    Only the managed regions and a few `<application>` attributes are
    written. Everything else - extra activities, receivers, providers,
    meta-data, hand-added permissions - is the developer's and is left
    exactly as it is.
    """
    notes: list[str] = []
    text = existing

    for kind in _MANIFEST_REGIONS:
        wanted = extract_region(rendered, kind)
        if wanted is None:
            continue
        block = _block(wanted)
        current = extract_region(text, kind)
        if current is not None:
            if _block(current) == block:
                continue
            text = replace_region(text, kind, block)
            notes.append(kind)
            continue
        # Region absent (hand-written or older manifest): add it where the
        # template puts it, so the next sync can update it in place.
        if not block:
            continue
        if kind == "permissions":
            match = _OPEN_MANIFEST.search(text)
            if match:
                text = (text[:match.end()] + "\n\n" + _wrapped(kind, block)
                        + text[match.end():])
                notes.append("permissions")
        elif kind == "activity":
            previous = _launcher_activity(text)
            if previous is not None:
                # A release before the activity region wrote the launcher
                # element inline: replace it instead of duplicating it.
                span_start, span_end = previous.start(), previous.end()
                while span_start > 0 and text[span_start - 1] in " \t":
                    span_start -= 1
                if text[span_end:span_end + 1] == "\n":
                    span_end += 1
                text = (text[:span_start] + _wrapped(kind, block) + "\n"
                        + text[span_end:])
                notes.append("activity")
                continue
            match = _APPLICATION.search(text)
            if match:
                text = (text[:match.end()] + "\n" + _wrapped(kind, block)
                        + text[match.end():])
                notes.append("activity")
        elif "</application>" in text:
            text = text.replace("</application>",
                                _wrapped(kind, block) + "\n    </application>", 1)
            notes.append("services")

    # Attributes pydrud.yaml owns. Only rewritten when already present, so a
    # developer who restructured the tag keeps their layout.
    rendered_app = _APPLICATION.search(rendered)
    current_app = _APPLICATION.search(text)
    if rendered_app and current_app:
        updated = current_app.group(0)
        for name in ("android:allowBackup", "android:usesCleartextTraffic",
                     "android:label", "android:theme"):
            value = _attr(rendered_app.group(0), name)
            if value is None:
                continue
            updated = _set_attr(updated, name, value)
        if updated != current_app.group(0):
            text = text[:current_app.start()] + updated + text[current_app.end():]
            notes.append("application attributes")

    return text, notes


# ── ProGuard ─────────────────────────────────────────────────────────────

def merge_proguard(existing: str, rendered: str) -> tuple[str, list[str]]:
    """Replace the `rules` region, keeping hand-written rules around it."""
    wanted = extract_region(rendered, "rules", "hash")
    if wanted is None:
        return existing, []
    block = _block(wanted)
    current = extract_region(existing, "rules", "hash")
    if current is None:
        # Legacy file: append the region after the developer's rules so the
        # generated block stays clearly separated from theirs.
        separator = "" if existing.endswith("\n\n") else (
            "\n" if existing.endswith("\n") else "\n\n")
        return existing + separator + block, ["proguard rules"]
    if _block(current) == block:
        return existing, []
    return replace_region(existing, "rules", block, "hash"), ["proguard rules"]


# ── Gradle ───────────────────────────────────────────────────────────────

#: Regions owned inside a Kotlin build script.
_GRADLE_REGIONS = ("deps", "pip")

_ASSIGN = re.compile(r"^(\s*)([A-Za-z_][A-Za-z0-9_.\[\]\"-]*)\s*(\+=|=)\s*(\S.*)$")
_CALL = re.compile(r"^(\s*)([A-Za-z_][A-Za-z0-9_.\[\]\"]*)\s*\((.*)\)\s*$")


def _line_key(line: str):
    """Identify the value a Kotlin line carries, for positional patching."""
    match = _ASSIGN.match(line)
    if match:
        return ("assign", match.group(2))
    match = _CALL.match(line)
    if match:
        return ("call", match.group(2))
    return None


def _region_lines(lines: list[str], kind: str) -> set[int]:
    """Line indices covered by a region, markers included."""
    begin, end = region_markers(kind, "kotlin")
    inside = False
    covered: set[int] = set()
    for index, line in enumerate(lines):
        if begin in line:
            inside = True
        if inside:
            covered.add(index)
        if end in line:
            inside = False
    return covered


def merge_gradle(existing: str, rendered: str) -> tuple[str, list[str]]:
    """Apply the rendered build script to *existing*, keeping local edits.

    Two mechanisms, in order:

    * the deps and pip regions are replaced wholesale, so dependency changes
      driven by pydrud.yaml (camera, Firebase, pydrud pip add) land in a
      script the developer has extended;
    * every scalar assignment and single-line call is matched by name and
      updated positionally, so minSdk, versionName, abiFilters and friends
      follow the YAML instead of being frozen at creation time.

    A block that cannot be patched line by line - a new plugin, a product
    flavor dimension - is reported as needing review, so the caller can put
    the freshly rendered file next to the project's own.
    """
    notes: list[str] = []
    text = existing

    for kind in _GRADLE_REGIONS:
        wanted = extract_region(rendered, kind, "kotlin")
        current = extract_region(text, kind, "kotlin")
        if wanted is None or current is None:
            continue
        block = _block(wanted)
        if _block(current) == block:
            continue
        text = replace_region(text, kind, block, "kotlin")
        notes.append("dependencies" if kind == "deps" else "pip packages")

    rendered_lines = rendered.splitlines()
    skip: set[int] = set()
    for kind in _GRADLE_REGIONS:
        skip |= _region_lines(rendered_lines, kind)

    wanted: dict = {}
    for index, line in enumerate(rendered_lines):
        if index in skip:
            continue
        key = _line_key(line)
        if key is not None:
            wanted.setdefault(key, []).append(line)

    current_lines = text.splitlines()
    positions: dict = {}
    for index, line in enumerate(current_lines):
        key = _line_key(line)
        if key is not None:
            positions.setdefault(key, []).append(index)

    changed = False
    structural = False
    for key, targets in wanted.items():
        hits = positions.get(key, [])
        if len(hits) != len(targets):
            structural = True
            continue
        for hit, target in zip(hits, targets):
            if current_lines[hit] != target:
                current_lines[hit] = target
                changed = True
    if changed:
        text = "\n".join(current_lines) + "\n"
        notes.append("values")
    if structural:
        notes.append(NEEDS_REVIEW)
    return text, notes


# ── Properties ───────────────────────────────────────────────────────────

_PROPERTY = re.compile(r"^\s*([A-Za-z0-9_.-]+)\s*=", re.MULTILINE)


def merge_properties(existing: str, rendered: str) -> tuple[str, list[str]]:
    """Add the keys Pydrud needs; never overwrite a value already set.

    `gradle.properties` is a developer-tunable file (heap size, caches,
    AndroidX flags). A project that raised `-Xmx` must keep its value, so
    only missing keys are appended.
    """
    present = set(_PROPERTY.findall(existing))
    additions = []
    for line in rendered.splitlines():
        if not line.strip() or line.lstrip().startswith(("#", "!")):
            continue
        match = _PROPERTY.match(line)
        if match and match.group(1) not in present:
            additions.append(line)
    if not additions:
        return existing, []
    text = existing if existing.endswith("\n") else existing + "\n"
    return text + "\n".join(additions) + "\n", ["gradle properties"]
