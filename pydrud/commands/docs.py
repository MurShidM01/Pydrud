def _signature(obj: Any) -> str:
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"


def _doc(obj: Any) -> str:
    return inspect.getdoc(obj) or ""


def _public_members(module) -> list[tuple[str, Any]]:
    names = getattr(module, "__all__", None)
    if names is None:
        names = [n for n in dir(module) if not n.startswith("_")]
    members = []
    for name in names:
        member = getattr(module, name, None)
        if member is None:
            continue
        if inspect.isclass(member) or inspect.isfunction(member):
            if getattr(member, "__module__", "").startswith(
                    module.__name__.split(".")[0]):
                members.append((name, member))
    return sorted(members, key=lambda item: item[0])


def _render_member(name: str, member: Any) -> str:
    out = [f'<h3 id="{html.escape(name)}">{html.escape(name)}'
           f'<span class="badge">'
           f'{"class" if inspect.isclass(member) else "function"}</span></h3>']
    out.append(f'<div class="sig">{html.escape(name + _signature(member))}</div>')
    doc = _doc(member)
    if doc:
        out.append(f'<p class="doc">{html.escape(doc)}</p>')
    if inspect.isclass(member):
        methods = [(n, m) for n, m in inspect.getmembers(member, inspect.isfunction)
                   if not n.startswith("_")]
        for method_name, method in sorted(methods)[:40]:
            out.append(f'<div class="sig">{html.escape(name)}.'
                       f'{html.escape(method_name + _signature(method))}</div>')
            summary = (_doc(method).splitlines() or [""])[0]
            if summary:
                out.append(f'<p class="doc">{html.escape(summary)}</p>')
    return "\n".join(out)


def _page(title: str, nav: str, body: str, version: str) -> str:
    return (f"<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>{html.escape(title)}</title><style>{_CSS}</style></head>"
            f"<body><header><h1>Pydrud</h1>"
            f"<span>v{version} — Android apps in Python</span></header>"
            f"<div class='wrap'><nav>{nav}</nav><main>{body}</main></div>"
            f"<footer>Generated by <code>pydrud docs</code>. "
            f"Everything here is introspected from the installed package.</footer>"
            f"</body></html>")


def build_docs(project_dir: str = ".", output: str = "docs") -> str:
    """Write the HTML reference and return the output directory."""
    import pydrud

    out_dir = os.path.join(project_dir, output)
    os.makedirs(out_dir, exist_ok=True)
    version = getattr(pydrud, "__version__", "")

    modules = ["pydrud", "pydrud.main", "pydrud.navigation",
               "pydrud.widgets", "pydrud.widgets.canvas",
               "pydrud.widgets.advanced", "pydrud.core.store",
               "pydrud.core.controllers", "pydrud.core.tasks",
               "pydrud.core.results", "pydrud.data.database",
               "pydrud.data.cache", "pydrud.services.native",
               "pydrud.services.http", "pydrud.packages", "pydrud.testing"]

    pages: list[tuple[str, str]] = []
    for name in modules:
        try:
            module = __import__(name, fromlist=["x"])
        except Exception:                                # pragma: no cover
            continue
        members = _public_members(module)
        if not members:
            continue
        body = [f"<h2>{html.escape(name)}</h2>"]
        doc = _doc(module)
        if doc:
            body.append(f'<p class="doc">{html.escape(doc)}</p>')
        body.extend(_render_member(n, m) for n, m in members)
        pages.append((name, "\n".join(body)))

    nav = "\n".join(f'<a href="{name.replace(".", "_")}.html">{name}</a>'
                    for name, _ in pages)
    nav = '<a href="index.html"><strong>Overview</strong></a>' + nav

    for name, body in pages:
        path = os.path.join(out_dir, f"{name.replace('.', '_')}.html")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(_page(name, nav, body, version))

    # Overview page: README if present, otherwise a module index.
    readme = os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(pydrud.__file__))), "README.md")
    overview = ["<h2>Overview</h2>"]
    if os.path.exists(readme):
        text = open(readme, encoding="utf-8").read()[:6000]
        overview.append(f'<p class="doc">{html.escape(text)}</p>')
    else:
        overview.append("<ul>" + "".join(
            f'<li><a href="{n.replace(".", "_")}.html">{n}</a></li>'
            for n, _ in pages) + "</ul>")
    index = os.path.join(out_dir, "index.html")
    with open(index, "w", encoding="utf-8") as handle:
        handle.write(_page("Pydrud API", nav, "\n".join(overview), version))

    return out_dir


def serve_docs(directory: str, port: int = 8000) -> None:        # pragma: no cover
    """Serve the generated docs locally."""
    import functools
    import http.server
    import socketserver

    handler = functools.partial(http.server.SimpleHTTPRequestHandler,
                                directory=directory)
    with socketserver.TCPServer(("0.0.0.0", port), handler) as server:
        print(f"  Serving {directory} on http://localhost:{port} (Ctrl-C to stop)")
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass
