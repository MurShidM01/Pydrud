"""
``pydrud docs`` — generate a static, offline API reference.

Everything is introspected from the installed package plus your own
``src/`` modules, so the docs can never drift from the code. The output is
a handful of self-contained HTML files; host them anywhere or open
``docs/index.html`` directly.
"""

from __future__ import annotations

import html
import inspect
import os
from typing import Any

